    def _resolve_report_models_and_pages(
        self,
        report: DiscoveredReport,
        scan_result: WorkspaceScanResult,
        bound_m: Optional[DiscoveredModel],
    ) -> Tuple[Dict[str, List[Dict[str, Any]]], List[Dict[str, Any]], Dict[str, int]]:
        """
        Resolves per-page referenced semantic models and the aggregate Models List for a report.
        Supports composite models where individual visuals/pages reference entities across multiple models.
        """
        def _model_to_info(m: DiscoveredModel, is_primary: bool = False) -> Dict[str, Any]:
            safe_m = sanitize_filename(m.name)
            scoped_m_cfg = self.config.get_scoped_config(m.artifact_id)
            t_cnt = len(m.get_published_tables(scoped_m_cfg))
            m_cnt = len(m.get_published_measures(scoped_m_cfg))
            return {
                "key": m.artifact_id,
                "name": m.name,
                "format": m.model_format,
                "scope": "Primary Bound Model (Local Workspace)" if is_primary else "Composite Model Reference (Local Workspace)",
                "is_local": True,
                "is_primary": is_primary,
                "tables_count": t_cnt,
                "measures_count": m_cnt,
                "md_url": f"../../models/{safe_m}/README.md",
                "html_url": f"../../models/{safe_m}/index{self.config.html_ext_suffix}",
            }

        primary_info: Optional[Dict[str, Any]] = None
        if bound_m:
            primary_info = _model_to_info(bound_m, is_primary=True)
        elif report.bound_model_name:
            primary_info = {
                "key": f"remote:{report.bound_model_name}",
                "name": report.bound_model_name,
                "format": "Remote",
                "scope": "Remote Fabric / PBI Service",
                "is_local": False,
                "is_primary": True,
                "tables_count": "—",
                "measures_count": "—",
                "md_url": None,
                "html_url": None,
            }

        all_models_by_key: Dict[str, Dict[str, Any]] = {}
        if primary_info:
            all_models_by_key[primary_info["key"]] = primary_info

        page_models_map: Dict[str, List[Dict[str, Any]]] = {}
        page_visual_counts: Dict[str, int] = {}
        page_visibility_map: Dict[str, bool] = {}
        preferred_name = bound_m.name if bound_m else None

        pages_by_name = {}
        if report.report_obj and report.report_obj.pages:
            for p_obj in report.report_obj.pages:
                pages_by_name[p_obj.display_name] = p_obj

        for p_name in report.page_names:
            p_obj = pages_by_name.get(p_name)
            page_visibility_map[p_name] = p_obj.is_hidden if p_obj else False
            p_models: Dict[str, Dict[str, Any]] = {}
            if p_obj:
                dyn_vis = [v for v in p_obj.visuals if v.is_dynamic]
                page_visual_counts[p_name] = len(dyn_vis)
                for v in p_obj.visuals:
                    cc = v.calculation_context
                    for m in cc.evaluated_metrics:
                        if bound_m and (m.field in bound_m.measures or m.table in bound_m.tables):
                            info = _model_to_info(bound_m, is_primary=True)
                            p_models[info["key"]] = info
                            all_models_by_key[info["key"]] = info
                        else:
                            m_matches = scan_result.find_measure(m.field, preferred_model=preferred_name)
                            if m_matches:
                                dm = m_matches[0][0]
                                info = _model_to_info(dm, is_primary=(bound_m is not None and dm.artifact_id == bound_m.artifact_id))
                                p_models[info["key"]] = info
                                all_models_by_key[info["key"]] = info
                            elif m.table:
                                t_matches = scan_result.find_table(m.table, preferred_model=preferred_name)
                                if t_matches:
                                    dm = t_matches[0]
                                    info = _model_to_info(dm, is_primary=(bound_m is not None and dm.artifact_id == bound_m.artifact_id))
                                    p_models[info["key"]] = info
                                    all_models_by_key[info["key"]] = info

                    table_refs = (
                        [s.table for s in cc.slicing_coordinates]
                        + [vf.table for vf in cc.visual_active_filters]
                        + [pf.table for pf in (cc.page_filters or (cc.locked_active_filters + cc.unlocked_available_filters))]
                        + [af.table for af in cc.all_pages_filters]
                        + [sl.table for sl in cc.page_slicers]
                    )
                    for t_ref in table_refs:
                        if not t_ref or t_ref == "Unknown":
                            continue
                        if bound_m and t_ref in bound_m.tables:
                            info = _model_to_info(bound_m, is_primary=True)
                            p_models[info["key"]] = info
                            all_models_by_key[info["key"]] = info
                        else:
                            t_matches = scan_result.find_table(t_ref, preferred_model=preferred_name)
                            if t_matches:
                                dm = t_matches[0]
                                info = _model_to_info(dm, is_primary=(bound_m is not None and dm.artifact_id == bound_m.artifact_id))
                                p_models[info["key"]] = info
                                all_models_by_key[info["key"]] = info
            else:
                page_visual_counts[p_name] = 0

            if not p_models and primary_info:
                p_models[primary_info["key"]] = primary_info

            page_models_map[p_name] = list(p_models.values())

        return page_models_map, list(all_models_by_key.values()), page_visual_counts, page_visibility_map

    def _build_report_overview_markdown(
        self,
        report: DiscoveredReport,
        scan_result: WorkspaceScanResult,
        bound_m: Optional[DiscoveredModel],
    ) -> str:
        """Builds Markdown overview for an individual report (reports/<ReportName>/README.md)."""
        scoped_cfg = self.config.get_scoped_config(report.artifact_id)
        page_models_map, all_report_models, page_visual_counts, page_visibility_map = self._resolve_report_models_and_pages(
            report, scan_result, bound_m
        )
        total_dyn_visuals = sum(page_visual_counts.values())

        header_block = "\n".join([
            f"# Report: {report.name}",
            "",
            f"**Artifact Type**: `Report` | **Format**: `{report.report_format}` | "
            f"**Total Pages**: `{len(report.page_names)}` | **Dynamic Visuals**: `{total_dyn_visuals}` | "
            f"**Referenced Models**: `{len(all_report_models)}`",
        ])

        # 1. Description
        desc_sec = DocSection(
            section_id="tab-desc",
            title="Description",
            nav_label="Description",
            content="\n".join([
                "## Description",
                "",
                f"> Power BI presentation and visual analytics catalog for report `{report.name}`. "
                "Documents canvas pages, layout structure, and underlying semantic model bindings (including composite model references).",
            ]),
        )

        # 2. Pages (with referenced models per page)
        pages_lines = ["## Report Canvas Pages", ""]
        if not scoped_cfg.include_visual_docs:
            pages_lines.append("> Visual page documentation has been excluded by configuration (`include_visual_docs = False`).")
        else:
            pages_lines.extend([
                "| # | Page Name | Referenced Models | Visibility | Dynamic Visuals | Visuals Catalog |",
                "| --- | --- | --- | :---: | :---: | --- |",
            ])
            for idx, p_name in enumerate(report.page_names, start=1):
                clean_p = sanitize_filename(p_name)
                p_mods = page_models_map.get(p_name, [])
                mod_links = []
                for pm in p_mods:
                    if pm.get("md_url"):
                        mod_links.append(f"[{pm['name']}]({pm['md_url']})")
                    else:
                        mod_links.append(f"`{pm['name']}`")
                mods_str = ", ".join(mod_links) if mod_links else "—"
                v_cnt = page_visual_counts.get(p_name, 0)
                is_hidden = page_visibility_map.get(p_name, False)
                vis_str = "Hidden" if is_hidden else "Visible"
                pages_lines.append(
                    f"| {idx} | **{p_name}** | {mods_str} | {vis_str} | `{v_cnt}` | [View Page Visuals & Metrics](visuals/{clean_p}.md) |"
                )

        pages_sec = DocSection(
            section_id="tab-pages",
            title=f"Pages ({len(report.page_names)})",
            nav_label=f"Pages ({len(report.page_names)})",
            content="\n".join(pages_lines),
        )

        # 3. Models List (Report Identity & Dataset Binding)
        models_lines = [
            "## Models List (Report Identity & Dataset Binding)",
            "",
            "| Semantic Model | Format | Binding Role & Scope | Tables | Measures | Documentation |",
            "| --- | --- | --- | :---: | :---: | --- |",
        ]
        if all_report_models:
            for rm in all_report_models:
                if rm.get("md_url"):
                    m_name_cell = f"**[{rm['name']}]({rm['md_url']})**"
                    doc_cell = f"[Open Model Catalog]({rm['md_url']})"
                else:
                    m_name_cell = f"**`{rm['name']}`**"
                    doc_cell = "*Remote / External*"
                models_lines.append(
                    f"| {m_name_cell} | `{rm['format']}` | {rm['scope']} | `{rm['tables_count']}` | `{rm['measures_count']}` | {doc_cell} |"
                )
        else:
            models_lines.append("| *Standalone / Unknown* | — | Standalone Report | — | — | — |")

        models_sec = DocSection(
            section_id="tab-models",
            title=f"Models List ({len(all_report_models)})",
            nav_label=f"Models List ({len(all_report_models)})",
            content="\n".join(models_lines),
        )

        return assemble_markdown_document(None, header_block, [desc_sec, pages_sec, models_sec])

