    def write_to_directory(
        self,
        scan_result: WorkspaceScanResult,
        output_dir: Union[str, Path],
        output_format: Optional[str] = None,
    ) -> Dict[str, List[str]]:
        """Writes multi-project workspace documentation to output_dir according to output_format."""
        out_path = Path(output_dir).resolve()
        fmt = (output_format or self.config.output_format or "html").lower()
        results: Dict[str, List[str]] = {"markdown": [], "html": []}

        # 1. Markdown Generation
        if fmt in ("markdown", "both"):
            md_dir = out_path / "markdown" if fmt == "both" else out_path
            print(f"[INFO] Compiling Markdown documentation...")
            md_docs = self.generate_all_markdown_documents(scan_result)
            print(f"[INFO] Writing {len(md_docs)} Markdown documents to '{md_dir}'...")
            for rel_file, content in md_docs.items():
                f_path = md_dir / rel_file
                f_path.parent.mkdir(parents=True, exist_ok=True)
                with open(f_path, "w", encoding="utf-8") as f:
                    f.write(content)
                results["markdown"].append(str(f_path))

        # 2. HTML Generation
        if fmt in ("html", "both"):
            html_dir = out_path / "html" if fmt == "both" else out_path
            print(f"[INFO] Compiling HTML portal pages...")
            html_docs = self.generate_all_html_documents(scan_result)
            print(f"[INFO] Writing {len(html_docs)} HTML & asset files to '{html_dir}'...")
            for rel_file, content in html_docs.items():
                f_path = html_dir / rel_file
                f_path.parent.mkdir(parents=True, exist_ok=True)
                with open(f_path, "w", encoding="utf-8") as f:
                    f.write(content)
                results["html"].append(str(f_path))

        return results

    def _create_link_resolvers(
        self,
        scan_result: WorkspaceScanResult,
        report: DiscoveredReport,
        bound_model: Optional[DiscoveredModel],
        current_doc_dir: str,
        ext: str,
    ) -> Tuple[Callable[[str], Optional[str]], Callable[[str, str], Optional[str]]]:
        """
        Creates table and measure relative URL resolvers that dynamically calculate the exact
        relative path from current_doc_dir to target models in the workspace via os.path.relpath.
        Supports composite models by checking bound_model first, then scanning all workspace models.
        """
        preferred_model_name = bound_model.name if bound_model else None

        def resolve_table_url(table_name: str) -> Optional[str]:
            if not self.config.include_models or not table_name or table_name == "Unknown":
                return None
            target_model: Optional[DiscoveredModel] = None

            # 1. Check bound model first
            if bound_model and table_name in bound_model.tables:
                # If table is inherited in bound_model, ascend to originating model
                is_inh = (hasattr(bound_model, "inherited_tables") and table_name in bound_model.inherited_tables)
                if is_inh:
                    curr_m = bound_model
                    visited_models = {curr_m.artifact_id}
                    while curr_m and (hasattr(curr_m, "inherited_tables") and table_name in curr_m.inherited_tables):
                        inh_name = curr_m.inherited_tables.get(table_name)
                        if not inh_name:
                            break
                        parent_m = scan_result.get_model(inh_name)
                        if not parent_m or parent_m.artifact_id in visited_models:
                            break
                        visited_models.add(parent_m.artifact_id)
                        curr_m = parent_m
                    if curr_m and curr_m != bound_model and table_name in curr_m.tables:
                        target_model = curr_m
                    else:
                        matches = scan_result.find_table(table_name, preferred_model=preferred_model_name)
                        if matches:
                            target_model = matches[0]
                else:
                    target_model = bound_model
            else:
                # 2. Check other workspace models (Composite Model)
                matches = scan_result.find_table(table_name, preferred_model=preferred_model_name)
                if matches:
                    target_model = matches[0]

            if not target_model:
                return None

            scoped_m_cfg = self.config.get_scoped_config(target_model.artifact_id)
            if scoped_m_cfg.is_table_excluded(table_name):
                return None

            # If table is still marked out_of_scope / inherited in target_model and include_inherited_entities is False,
            # no file was generated, so return None to prevent broken links
            if not scoped_m_cfg.include_inherited_entities and hasattr(target_model, "inherited_tables") and table_name in target_model.inherited_tables:
                return None

            clean_tbl = sanitize_filename(table_name)
            safe_m = sanitize_filename(target_model.name)
            tbl_sub = scoped_m_cfg.tables_subdir.strip("/\\")
            target_doc_path = f"models/{safe_m}/{tbl_sub}/{clean_tbl}.{ext}"
            rel_link = os.path.relpath(target_doc_path, current_doc_dir).replace("\\", "/")
            return rel_link

        def resolve_measure_url(table_name: str, measure_name: str) -> Optional[str]:
            if not self.config.include_models or not measure_name:
                return None
            target_model: Optional[DiscoveredModel] = None
            target_table: str = table_name

            # 1. Check bound model first
            if bound_model and measure_name in bound_model.measures:
                is_inh = (hasattr(bound_model, "inherited_measures") and measure_name in bound_model.inherited_measures)
                if is_inh:
                    curr_m = bound_model
                    visited_models = {curr_m.artifact_id}
                    while curr_m and (hasattr(curr_m, "inherited_measures") and measure_name in curr_m.inherited_measures):
                        inh_name = curr_m.inherited_measures.get(measure_name)
                        if not inh_name:
                            break
                        parent_m = scan_result.get_model(inh_name)
                        if not parent_m or parent_m.artifact_id in visited_models:
                            break
                        visited_models.add(parent_m.artifact_id)
                        curr_m = parent_m
                    if curr_m and curr_m != bound_model and measure_name in curr_m.measures:
                        target_model = curr_m
                        target_table = curr_m.measures.get(measure_name, target_table)
                    else:
                        matches = scan_result.find_measure(measure_name, preferred_model=preferred_model_name)
                        if matches:
                            target_model, target_table = matches[0]
                else:
                    target_model = bound_model
                    target_table = bound_model.measures[measure_name]
            else:
                # 2. Check other workspace models (Composite Model)
                matches = scan_result.find_measure(measure_name, preferred_model=preferred_model_name)
                if matches:
                    target_model, target_table = matches[0]

            if not target_model:
                return None

            scoped_m_cfg = self.config.get_scoped_config(target_model.artifact_id)
            if scoped_m_cfg.is_table_excluded(target_table):
                return None

            # If measure is still marked out_of_scope / inherited in target_model and include_inherited_entities is False,
            # no file was generated, so return None
            if not scoped_m_cfg.include_inherited_entities and hasattr(target_model, "inherited_measures") and measure_name in target_model.inherited_measures:
                return None

            clean_tbl = sanitize_filename(target_table or "Model")
            clean_m = sanitize_filename(measure_name)
            safe_m = sanitize_filename(target_model.name)
            meas_sub = scoped_m_cfg.measures_subdir.strip("/\\")
            target_doc_path = f"models/{safe_m}/{meas_sub}/{clean_tbl}/{clean_m}.{ext}"
            rel_link = os.path.relpath(target_doc_path, current_doc_dir).replace("\\", "/")
            return rel_link

        return resolve_table_url, resolve_measure_url

    def _build_workspace_index_markdown(self, scan_result: WorkspaceScanResult) -> str:
        """Builds Markdown master workspace catalog (README.md)."""
        lines = []
        workspace_name = clean_project_name(scan_result.root_path.name)
        folder_depth = getattr(self.config, "workspace_folder_depth", 1) or 1
        folders = scan_result.get_artifacts_by_folder(folder_depth=folder_depth)
        total_tables = sum(
            len(m.get_published_tables(self.config.get_scoped_config(m.artifact_id)))
            for m in scan_result.models.values()
        )
        total_measures = sum(
            len(m.get_published_measures(self.config.get_scoped_config(m.artifact_id)))
            for m in scan_result.models.values()
        )
        total_pages = sum(len(r.page_names) for r in scan_result.reports.values())

        lines.append(f"# {workspace_name} - Workspace Documentation Catalog\n")
        lines.append(f"> Unified inventory and cross-artifact lineage for workspace `{workspace_name}`.\n")

        # KPI Summary Table
        lines.append("## Workspace Overview\n")
        lines.append("| Metric | Count | Details |")
        lines.append("| --- | --- | --- |")
        lines.append(f"| **Repository Projects** | `{len(folders)}` | Logical directories / subfolders in codebase |")
        lines.append(f"| **Semantic Models** | `{len(scan_result.models)}` | Tabular datasets |")
        lines.append(f"| **Reports & Dashboards** | `{len(scan_result.reports)}` | PBIR / Legacy presentation items |")
