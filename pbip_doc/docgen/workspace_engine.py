def _expression_to_dict(exp: Any) -> Dict[str, Any]:
    if hasattr(exp, "to_dict"):
        return exp.to_dict()
    if isinstance(exp, dict):
        return exp
    if is_dataclass(exp):
        return asdict(exp)
    return {}

